/**
 * UploadFileUseCase — Validates and uploads a file via FileStorageProtocol.
 *
 * Validates:
 * - File size max 10 MB
 * - MIME type allowlist (image/jpeg, image/png, application/pdf,
 *   application/vnd.openxmlformats-officedocument.spreadsheetml.sheet)
 * - Generates UUID-based filename
 * - Stores at {tenantId}/{domain}/{filename}
 *
 * @see Requirements 26.2, 26.3, 26.5
 */

import type { DomainResult } from '@core/utils';
import { ok, fail } from '@core/utils';
import type { FileStorageProtocol } from '@core/protocols';
import type { FileUploadResult } from '../entities';
import { fileInvalidType, fileSizeExceeded } from '../errors/fileStorageErrors';

const MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024; // 10 MB

const ALLOWED_MIME_TYPES = new Set([
  'image/jpeg',
  'image/png',
  'application/pdf',
  'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
]);

export interface UploadFileInput {
  readonly tenantId: string;
  readonly domain: string;
  readonly buffer: Buffer;
  readonly originalFilename: string;
  readonly mimeType: string;
  readonly sizeBytes: number;
}

export interface UploadFileUseCase {
  execute(input: UploadFileInput): Promise<DomainResult<FileUploadResult>>;
}

export const UploadFileUseCaseImpl = ({
  fileStorageProtocol,
}: {
  fileStorageProtocol: FileStorageProtocol;
}): UploadFileUseCase => ({
  execute: async (input) => {
    // Validate file size
    if (input.sizeBytes > MAX_FILE_SIZE_BYTES) {
      return fail(fileSizeExceeded());
    }

    // Validate MIME type
    if (!ALLOWED_MIME_TYPES.has(input.mimeType)) {
      return fail(fileInvalidType());
    }

    // Delegate to FileStorageProtocol (UUID filename generated by protocol)
    const metadata = await fileStorageProtocol.upload({
      buffer: input.buffer,
      originalFilename: input.originalFilename,
      mimeType: input.mimeType,
      sizeBytes: input.sizeBytes,
      tenantId: input.tenantId,
      domain: input.domain,
    });

    return ok<FileUploadResult>({
      key: metadata.key,
      filename: metadata.filename,
      mimeType: metadata.mimeType,
      sizeBytes: metadata.sizeBytes,
    });
  },
});
